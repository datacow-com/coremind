def load_sample_image(name: str) -> bytes | None:
    """
    加载样本图像
    
    Args:
        name: 样本文件名
        
    Returns:
        bytes | None: 图像数据，如果不存在返回 None
    """
    sample_path = SAMPLES_DIR / name
    if sample_path.exists():
        return sample_path.read_bytes()
    return None


